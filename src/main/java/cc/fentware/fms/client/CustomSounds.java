package cc.fentware.fms.client;

import net.fabricmc.loader.api.FabricLoader;

import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.Comparator;
import java.util.List;

/**
 * Discovers OGGs in config/fms/sounds and generates an unpacked Minecraft resource pack.
 * The generated pack must be enabled once under Options > Resource Packs.
 * Minecraft must reload resources (F3+T) after a change.
 */
public final class CustomSounds {
    public static final int MAX_SOUNDS = 16;
    private static final long MAX_BYTES = 8L * 1024L * 1024L;
    public static final Path DIRECTORY = FabricLoader.getInstance().getConfigDir().resolve("fms").resolve("sounds");
    private static final Path PACK = FabricLoader.getInstance().getGameDir().resolve("resourcepacks")
            .resolve("FMS Custom Sounds");
    private static List<String> files = List.of();
    private static String status = "Not scanned";

    private CustomSounds() {}

    public static List<String> names() { return files; }
    public static String status() { return status; }
    public static String slotId(int index) { return "custom_" + index; }

    public static int indexOf(String selected) {
        if (!selected.startsWith("custom:")) return -1;
        return files.indexOf(selected.substring("custom:".length()));
    }

    public static String next(String current, String[] stock) {
        ArrayList<String> all = new ArrayList<>(Arrays.asList(stock));
        all.addAll(files.stream().map(s -> "custom:" + s).toList());
        int index = all.indexOf(current);
        return all.get((index + 1 + all.size()) % all.size());
    }

    public static boolean valid(String name, String[] stock) {
        if (Arrays.asList(stock).contains(name)) return true;
        return indexOf(name) >= 0;
    }

    public static void refresh() {
        try {
            Files.createDirectories(DIRECTORY);
            List<String> found;
            try (var stream = Files.list(DIRECTORY)) {
                found = stream
                        .filter(Files::isRegularFile)
                        .filter(p -> p.getFileName().toString().matches("[a-zA-Z0-9_-]{1,48}\\.ogg"))
                        .filter(p -> validOgg(p))
                        .sorted(Comparator.comparing(p -> p.getFileName().toString()))
                        .limit(MAX_SOUNDS)
                        .map(p -> p.getFileName().toString().replaceFirst("\\.ogg$", ""))
                        .toList();
            }
            files = List.copyOf(found);
            Path assets = PACK.resolve("assets").resolve("fms_custom");
            Path clips = assets.resolve("sounds").resolve("clips");
            Files.createDirectories(clips);
            Files.writeString(PACK.resolve("pack.mcmeta"), """
                    {"pack":{"description":"FMS user warning audio - generated by FMS",
                    "min_format":[97,1],"max_format":[97,1]}}
                    """, StandardCharsets.UTF_8);
            StringBuilder soundJson = new StringBuilder("{");
            for (int i = 0; i < files.size(); i++) {
                if (i > 0) soundJson.append(',');
                soundJson.append('"').append(slotId(i)).append("\":{\"sounds\":[\"fms_custom:clips/")
                        .append(slotId(i)).append("\"]}");
                Files.copy(DIRECTORY.resolve(files.get(i) + ".ogg"),
                        clips.resolve(slotId(i) + ".ogg"), java.nio.file.StandardCopyOption.REPLACE_EXISTING);
            }
            // Remove any stale slots when files are deleted.
            for (int i = files.size(); i < MAX_SOUNDS; i++) Files.deleteIfExists(clips.resolve(slotId(i) + ".ogg"));
            soundJson.append('}');
            Files.writeString(assets.resolve("sounds.json"), soundJson.toString(), StandardCharsets.UTF_8);
            status = files.size() + " clip(s) found - enable/reload resource pack";
        } catch (Exception e) {
            status = "Sound refresh failed: " + e.getMessage();
            System.err.println("[FMS] " + status);
        }
    }

    private static boolean validOgg(Path path) {
        try {
            if (Files.size(path) > MAX_BYTES || Files.size(path) < 4) return false;
            try (InputStream stream = Files.newInputStream(path)) {
                byte[] magic = stream.readNBytes(4);
                return Arrays.equals(magic, new byte[]{'O', 'g', 'g', 'S'});
            }
        } catch (IOException e) {
            return false;
        }
    }

}
